//! IEEE 1800-2023 clause 5: lexical conventions.

use crate::harness::{Order, check};

// §5.4, §5.6, §5.6.1, §5.7.1, §5.7.2, §5.8, ...: comments, identifiers, integer/real/time/string literals, attributes
